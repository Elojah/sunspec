// Command modelgen generates model/models.go from SunSpec's model definitions, vendored in json/ at the commit json/REF
// names: `go generate ./model` runs it, and `make models` vendors another commit first.
//
// It parses each definition with model.Parse, and writes them as Go literals, sorted by ID, so that the library reads
// no JSON at run time, and costs nothing at init.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/elojah/sunspec/model"
)

func main() {
	in := flag.String("in", "json", "directory of the model_*.json definitions, and of REF")
	out := flag.String("out", "../../model/models.go", "file to write")
	flag.Parse()

	if err := run(*in, *out); err != nil {
		log.Fatal(err)
	}
}

func run(in, out string) error {
	ref, err := os.ReadFile(filepath.Join(in, "REF")) //nolint:gosec // the vendored definitions
	if err != nil {
		return err
	}
	paths, err := filepath.Glob(filepath.Join(in, "model_*.json"))
	if err != nil {
		return err
	}
	definitions := make([]*model.Definition, 0, len(paths))
	for _, path := range paths {
		d, err := parse(path)
		if err != nil {
			return err
		}
		definitions = append(definitions, d)
	}
	slices.SortFunc(definitions, func(a, b *model.Definition) int { return int(a.ID) - int(b.ID) })

	src, err := format.Source(generate(strings.TrimSpace(string(ref)), definitions))
	if err != nil {
		return err
	}

	return os.WriteFile(out, src, 0o600)
}

func parse(path string) (*model.Definition, error) {
	f, err := os.Open(path) //nolint:gosec // the vendored definitions
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()

	d, err := model.Parse(f)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}

	return d, nil
}

// generate writes definitions as the source of package model, unformatted: their IDs, and the definitions in their
// binary form, one after the other, in a string constant, with where each starts.
//
// A constant rather than a table of literals: on a microcontroller, a package-level variable holding slices sits in
// RAM, since Go lets it change, while a constant stays in flash. A Pico has 264 KB of RAM, which SunSpec's models in a
// table overflow. Lookup decodes a definition on first use, its strings slices of the constant.
func generate(ref string, definitions []*model.Definition) []byte {
	var (
		encoded []byte
		ids     = make([]string, 0, len(definitions))
		offsets = make([]string, 0, len(definitions)+1)
	)
	for _, d := range definitions {
		ids = append(ids, strconv.Itoa(int(d.ID)))
		offsets = append(offsets, strconv.Itoa(len(encoded)))
		data, err := d.MarshalBinary()
		if err != nil {
			log.Fatal(err)
		}
		encoded = append(encoded, data...)
	}
	offsets = append(offsets, strconv.Itoa(len(encoded)))

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/modelgen from github.com/sunspec/models at %s. DO NOT EDIT.\n\n", ref)
	b.WriteString("package model\n\n")
	b.WriteString("// ids holds the IDs of SunSpec's models, sorted, and offsets where each starts in encoded, which ends where the\n")
	b.WriteString("// next starts.\n")
	fmt.Fprintf(&b, "var (\nids = [...]uint16{%s}\n", strings.Join(ids, ", "))
	fmt.Fprintf(&b, "offsets = [...]uint32{%s}\n)\n\n", strings.Join(offsets, ", "))
	b.WriteString("// encoded holds SunSpec's models, in Definition.MarshalBinary's form. Their descriptions are in the JSON they come\n")
	fmt.Fprintf(&b, "// from, at https://github.com/sunspec/models/tree/%s/json.\n", ref)
	b.WriteString("const encoded = \"\" +\n")
	const chunk = 64
	for i := 0; i < len(encoded); i += chunk {
		b.WriteString(strconv.Quote(string(encoded[i:min(i+chunk, len(encoded))])))
		if i+chunk < len(encoded) {
			b.WriteString(" +")
		}
		b.WriteString("\n")
	}

	return b.Bytes()
}
